"""Re-skin the buoy stability explorer for the public site.

The explorer is generated by ``mechanical/simulations/buoy-stability/run_studies.py`` as one
self-contained HTML file (geometry and results embedded, no external requests). This turns that
file into the page the Technology page embeds: the site's sand canvas, DM Sans / JetBrains Mono
from ``assets/fonts/``, the lagoon accent, and a plain-language intro in place of the generator
note. Only the head, style block and first paragraph change; the script and data are untouched.

Refresh after the simulator is re-run::

    python3 -m telemetry.site.stability_embed <path to stability-explorer.html>

which rewrites ``static/stability/index.html`` (run from ``analytics/``).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

_OUT = Path(__file__).parent / "static" / "stability" / "index.html"

# The same warm tokens the rest of the site uses (theme/tokens.py), as literals because this
# page is a separate document inside an iframe and cannot see the site's stylesheet.
_STYLE = (Path(__file__).parent / "stability-theme.css").read_text(encoding="utf-8").strip()

_INTRO = ('<p class="note"><b>Slide through the designs, change the payload weight, read the verdict.</b> '
          'Arrow keys work too. Everything shown is calculated from the CAD, not drawn.</p>')

# Plain names under each readout, so a visitor never has to know what "GM" means.
_CARDS = {"Total mass": "what it weighs", "Draft": "how deep it sits", "Freeboard": "height above water",
          "GM": "stiffness, higher is better", "Max righting": "strongest push upright",
          "Tips over at": "point of no return"}

# Visible wording swaps (old -> new). Each must exist exactly once or themed() raises.
_WORDS = [
    ("Electronics housing, loaded", "Payload weight (electronics housing)"),
    ("Righting arm GZ vs heel", "Push back upright vs tilt"),
    ("heel angle, deg", "tilt angle (degrees)"),
    ("Green: rights itself \u00b7 Red: keeps rolling to inverted", "Green: pushes back upright \u00b7 Red: tips it further"),
]

_VERDICT = '<div id="verdict" class="verdict" role="status" aria-live="polite"></div>'

_KEY = ('<p class="key"><span><i class="g"></i><b>G</b> weight centre</span>'
        '<span><i class="b"></i><b>B</b> lift centre</span>'
        '<span><i class="m"></i><b>M</b> tilt pivot</span>'
        '<span>M above G means stable</span></p>')

# Runs after the explorer's own script. The verdict is read back from the readout cards, so it can
# never disagree with the numbers beside it; a MutationObserver re-reads it on every update.
_VERDICT_JS = """<script>
(function(){const $=i=>document.getElementById(i),n=t=>parseFloat($(t).textContent);
function verdict(){const v=$('verdict'),tip=$('rV').textContent.trim();
 let cls='na',head='No stability result for this design',sub='It is a section view only: no mass budget is on record yet.';
 if(tip!=='\u2013'){const fb=n('rF'),gm=n('rGM'),T=$('rT').textContent,F=$('rF').textContent;
  sub='Sits '+T+' deep with '+F+' above the water.';
  if(gm<=0){cls='bad';head='Unstable: it flips over on its own'}
  else if(fb<=0){cls='bad';head='Sinks: the top is under water'}
  else if(tip==='never'){cls='good';head='Stays upright. It rights itself from any tilt.'}
  else{cls='warn';head='Stable, but flips if tilted past '+tip}}
 v.className='verdict '+cls;v.innerHTML='<b>'+head+'</b><span>'+sub+'</span>'}
new MutationObserver(verdict).observe(document.querySelector('.row'),{subtree:true,childList:true,characterData:true});
verdict()})();
</script>"""


def _swap(text: str, old: str, new: str) -> str:
    """Replace one required occurrence, failing loudly if the explorer markup has moved on."""
    if text.count(old) != 1:
        raise ValueError(f"explorer markup changed; {old[:40]!r} not found exactly once")
    return text.replace(old, new)


def themed(raw: str) -> str:
    out = re.sub(r"<style>.*?</style>", lambda _: _STYLE, raw, count=1, flags=re.S)
    out = re.sub(r"<title>.*?</title>", "<title>Buoy stability explorer · S.C.O.U.T.</title>", out, count=1)
    out = re.sub(r"<h1>.*?</h1>", "<h1>Buoy stability explorer</h1>", out, count=1)
    out = re.sub(r'<p class="note">Generated by.*?</p>', lambda _: _INTRO, out, count=1, flags=re.S)
    for label, sub in _CARDS.items():
        out = _swap(out, f'<div class="l">{label}</div>', f'<div class="l">{label}<span class="s">{sub}</span></div>')
    for old, new in _WORDS:
        out = _swap(out, old, new)
    out = _swap(out, '<div class="ctl"><span id="capL"></span>',
                '<details class="how"><summary>How this design was modelled</summary><span id="capL"></span></details>\n<div class="ctl">')
    out = _swap(out, '<div class="row">', _VERDICT + '\n<div class="row">')
    out = _swap(out, "</svg>\n<script>", "</svg>\n" + _KEY + "\n<script>")
    out = _swap(out, "</script>\n</body>", "</script>\n" + _VERDICT_JS + "\n</body>")
    if "Generated by" in out or "#f8f3ef" not in out:
        raise ValueError("explorer markup changed; update stability_embed.py")
    return out


if __name__ == "__main__":
    _OUT.parent.mkdir(parents=True, exist_ok=True)
    _OUT.write_text(themed(Path(sys.argv[1]).read_text(encoding="utf-8")), encoding="utf-8")
    print(f"wrote {_OUT}")
