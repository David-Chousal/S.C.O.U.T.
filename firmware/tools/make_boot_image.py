#!/usr/bin/env python3
"""Build the scout_boot stub and write it into src/ota/scout_boot_image.h (SCO-197).

Every SCOUT_OTA application carries the stub at 0x2000 (src/ota/boot_section.cpp), so the stub's
bytes are generated, like Arduino's own SDU stubs. Run this from anywhere after changing
src/boot/ or lib/scout_fw_state, then rebuild the application:

    python3 firmware/tools/make_boot_image.py

It refuses a stub over 24 KB: the application starts at 0x8000, so a bigger stub would overlap it.

``--check`` builds the stub and exits 1 if the committed header no longer matches it. Run it on
macOS before merging a src/boot/ change. It is not in CI: a Linux build of the same sources comes
out a few bytes different (same text, so the link order, not a path), so only a macOS build
matches the committed header.
"""

from __future__ import annotations

import argparse
import hashlib
import pathlib
import re
import subprocess
import sys

FIRMWARE = pathlib.Path(__file__).resolve().parents[1]
BIN = FIRMWARE / ".pio" / "build" / "scout_boot" / "firmware.bin"
HEADER = FIRMWARE / "src" / "ota" / "scout_boot_image.h"
STUB_MAX = 0x6000


def render(stub: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in stub[i:i + 16]) + "," for i in range(0, len(stub), 16)]
    return (
        f"/* Generated by tools/make_boot_image.py from env scout_boot; do not edit.\n"
        f" * {len(stub)} bytes of {STUB_MAX}, sha256 {hashlib.sha256(stub).hexdigest()} */\n"
        + "\n".join(rows) + "\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed header is stale")
    args = parser.parse_args()
    subprocess.run(["pio", "run", "-e", "scout_boot"], cwd=FIRMWARE, check=True)
    stub = BIN.read_bytes()
    if len(stub) > STUB_MAX:
        sys.exit(f"scout_boot is {len(stub)} bytes, over the {STUB_MAX}-byte slot")
    if args.check:
        if HEADER.read_text() != render(stub):
            # Text in the stub is the usual cause of a build that differs between machines.
            for text in re.findall(rb"[ -~]{8,}", stub):
                print(f"  stub text: {text.decode()}")
            sys.exit(f"{HEADER.relative_to(FIRMWARE)} is stale ({len(stub)} B, sha256 "
                     f"{hashlib.sha256(stub).hexdigest()}): run tools/make_boot_image.py and commit it")
        print(f"{HEADER.relative_to(FIRMWARE)}: matches the scout_boot build")
        return
    HEADER.write_text(render(stub))
    print(f"{HEADER.relative_to(FIRMWARE)}: {len(stub)} bytes ({STUB_MAX - len(stub)} free)")


if __name__ == "__main__":
    main()
